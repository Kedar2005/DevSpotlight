const mkPage = async () => {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 } });
  const page = await ctx.newPage();
  page.on("console", (m) => m.type() === "error" && consoleErrors.push(m.text()));
  page.on("pageerror", (e) => consoleErrors.push("PAGEERROR " + e.message));
  return page;
};
const register = async (page, u) => {
  await page.goto(APP + "/register");
  await page.fill("#fullName", u.fullName); await page.fill("#userName", u.userName);
  await page.fill("#email", u.email); await page.fill("#password", u.password);
  await page.fill("#bio", "CS student who likes building things.");
  await page.click("button[type=submit]");
  await page.waitForURL("**/dashboard");
};

